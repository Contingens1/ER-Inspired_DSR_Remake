"""Gaping Dragon (c5260, AI 526000) battle script for DSR modelled on Nightreign's 770000 (DragonZombie).

NR uses the same attacks 3000-3010 as DS1 (work/boss_ai/nr_770000/770000_battle.lua); what differs is the choice:
  - attack picked by distance zone and by the side the player is on (grab with the hand on that side,
    tail whip / jump when the player is behind, vomit from 70 % HP);
  - cooldowns per attack (NR SetCoolTime: 3000/3010 15 s, 3001 20 s, 3002 10 s, 3003 35 s, 3005/3006 20 s,
    3007/3009 20 s, 3008 40 s; a cooled attack keeps weight 1);
  - 3003 belly flop always runs on into the 3004 charge (NR: SpEffect 46560 from 3003's TAE at 3.87 s);
  - below 70 % HP the first action is the big vomit 3008 (NR: until SpEffect 46599 from 3008's TAE);
  - after a successful grab the dragon backs off instead of waiting.

DS1 has no SetCoolTime / GetAttackPassedTime / SpEffect observers, so:
  - cooldowns = AI timers 0-4 (the indices DS1 scripts use) for the long ones; the two short ones (grab 15 s,
    swipe 10 s) count actions instead (AI numbers 2 and 3);
  - 46599 -> AI number 1, 46550 (tail cut) -> GetPartsDmg(tail) as in the DS1 script, 46560 -> combo 3003 -> 3004;
  - DS1 GetDist is measured between the capsules (it goes negative under the body), so the NR zones (5 / 10 m from
    the centre) become 3 / 8 m here, and the reach of each attack comes from the DS1 script (grabs <= 0.5 m,
    slam 1.5 m, swipe 4 m, flop 6 m, forward jump 8-14 m);
  - the forward jump 3009 covers 16.8 m (NR scales it to the target with TAE 760); closer than 8 m the dragon
    jumps in place (3007) instead.
Front attacks turn to the player first (turn time 1.5 s, 30 deg), directional ones (grabs, tail, jump in place)
fire at once, as in NR.

  python tools/make_gaping_ai.py            # writes work/boss_ai/526000_battle.nr_ai.lua and the luabnd
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_LUA = ROOT / "work" / "boss_ai" / "526000_battle.nr_ai.lua"
OUT_BND = ROOT / "dist" / "mods" / "bossy_nightreign" / "files_c5260_ai" / "script" / "m10_00_00_00.luabnd.dcx"

LUA = r'''REGISTER_GOAL(GOAL_Donsyoku526000_Battle, "Donsyoku526000Battle")
REGISTER_GOAL_NO_UPDATE(GOAL_Donsyoku526000_Battle, 1)

-- (mod) Nightreign-style choice of attacks, generated by tools/make_gaping_ai.py
-- timers: 0 flop+charge 35 s, 1 vomit 40 s, 2 jumps 20 s, 3 tail 20 s, 4 slam 20 s
-- numbers: 1 = vomit done (NR SpEffect 46599), 2 = grab cooldown (actions), 3 = swipe cooldown (actions)

function Donsyoku526000_Cool(ai, odds, timerNo)
    if 0 < odds and ai:IsFinishTimer(timerNo) == false then
        return 1
    end
    return odds
end

function Donsyoku526000_CoolN(ai, odds, numberNo)
    if 0 < odds and 0 < ai:GetNumber(numberNo) then
        return 1
    end
    return odds
end

function Donsyoku526000Battle_Activate(ai, goal)
    local targetDist = ai:GetDist(TARGET_ENE_0)
    local hprate = ai:GetHpRate(TARGET_SELF)
    local front = ai:IsInsideTarget(TARGET_ENE_0, AI_DIR_TYPE_F, 120)
    local left = ai:IsInsideTarget(TARGET_ENE_0, AI_DIR_TYPE_L, 120)
    local right = ai:IsInsideTarget(TARGET_ENE_0, AI_DIR_TYPE_R, 120)
    local low = hprate < 0.7
    local w1 = 0
    local w2 = 0
    local w3 = 0
    local w4 = 0
    local w5 = 0
    local w6 = 0
    local w7 = 0
    local w8 = 0
    local w30 = 0
    local w31 = 0
    local w32 = 0
    if 0 < ai:GetNumber(2) then
        ai:SetNumber(2, ai:GetNumber(2) - 1)
    end
    if 0 < ai:GetNumber(3) then
        ai:SetNumber(3, ai:GetNumber(3) - 1)
    end
    if low and ai:GetNumber(1) == 0 then
        w7 = 100
    elseif 8 <= targetDist then
        if front then
            w3 = 50
            w4 = 70
            w8 = 50
            w30 = 50
        else
            w30 = 100
            w32 = 30
        end
    elseif 3 <= targetDist then
        if front then
            w3 = 50
            w4 = 70
            w8 = 50
            w30 = 50
        elseif left or right then
            w30 = 100
            w31 = 30
            w32 = 30
            if low then
                w7 = 100
            end
        else
            w4 = 70
            w5 = 70
            w6 = 50
            w30 = 30
            if low then
                w7 = 100
            end
        end
    else
        if front then
            w2 = 50
            w3 = 50
            w4 = 70
            w6 = 50
            w8 = 50
            w31 = 10
        elseif left then
            w1 = 100
            w2 = 50
            w3 = 50
            w4 = 70
            w6 = 50
            w8 = 50
            w30 = 30
            w31 = 30
        elseif right then
            w1 = 100
            w4 = 70
            w6 = 50
            w8 = 50
            w30 = 30
            w31 = 30
        else
            w4 = 70
            w5 = 70
            w6 = 50
            w30 = 30
        end
        if low then
            w7 = 100
        end
    end
    if 0.5 < targetDist then
        w1 = 0
    end
    w1 = Donsyoku526000_CoolN(ai, w1, 2)
    w2 = Donsyoku526000_Cool(ai, w2, 4)
    w3 = Donsyoku526000_CoolN(ai, w3, 3)
    w4 = Donsyoku526000_Cool(ai, w4, 0)
    w5 = Donsyoku526000_Cool(ai, w5, 3)
    w6 = Donsyoku526000_Cool(ai, w6, 2)
    w7 = Donsyoku526000_Cool(ai, w7, 1)
    w8 = Donsyoku526000_Cool(ai, w8, 2)
    local total = w1 + w2 + w3 + w4 + w5 + w6 + w7 + w8 + w30 + w31 + w32
    if total < 1 then
        Donsyoku526000_Act30(ai, goal)
        return
    end
    local fateAct = ai:GetRandam_Int(1, total)
    if fateAct <= w1 then
        Donsyoku526000_Act01(ai, goal)
    elseif fateAct <= w1 + w2 then
        Donsyoku526000_Act02(ai, goal)
    elseif fateAct <= w1 + w2 + w3 then
        Donsyoku526000_Act03(ai, goal)
    elseif fateAct <= w1 + w2 + w3 + w4 then
        Donsyoku526000_Act04(ai, goal)
    elseif fateAct <= w1 + w2 + w3 + w4 + w5 then
        Donsyoku526000_Act05(ai, goal)
    elseif fateAct <= w1 + w2 + w3 + w4 + w5 + w6 then
        Donsyoku526000_Act06(ai, goal)
    elseif fateAct <= w1 + w2 + w3 + w4 + w5 + w6 + w7 then
        Donsyoku526000_Act07(ai, goal)
    elseif fateAct <= w1 + w2 + w3 + w4 + w5 + w6 + w7 + w8 then
        Donsyoku526000_Act08(ai, goal)
    elseif fateAct <= w1 + w2 + w3 + w4 + w5 + w6 + w7 + w8 + w30 then
        Donsyoku526000_Act30(ai, goal)
    elseif fateAct <= w1 + w2 + w3 + w4 + w5 + w6 + w7 + w8 + w30 + w31 then
        Donsyoku526000_Act31(ai, goal)
    else
        Donsyoku526000_Act32(ai, goal)
    end
    return
end

-- front attack: turn to the player (1.5 s, 30 deg), then attack from any angle; combo flag = the next action
-- may start at the TAE combo window, as NR's ComboTunable_SuccessAngle180
function Donsyoku526000_Front(goal, animId)
    goal:AddSubGoal(GOAL_COMMON_CommonAttack, 15, animId, TARGET_ENE_0, DIST_None, 180, 1.5, 30, true, true, false, false, 0, 0)
end

-- directional attack (the animation itself aims at a side): no turn first
function Donsyoku526000_Now(goal, animId)
    goal:AddSubGoal(GOAL_COMMON_ComboTunable_SuccessAngle180, 15, animId, TARGET_ENE_0, DIST_None, 0, 0, 0, 0)
end

function Donsyoku526000_Approach(ai, goal, dist)
    local targetDist = ai:GetDist(TARGET_ENE_0)
    if dist < targetDist then
        goal:AddSubGoal(GOAL_COMMON_ApproachTarget, 10, TARGET_ENE_0, dist, TARGET_SELF, targetDist < dist + 10, -1)
    end
end

-- grab with the hand on the player's side: 3000 right hand, 3010 left hand
function Donsyoku526000_Act01(ai, goal)
    ai:SetNumber(2, 2)
    if ai:IsInsideTarget(TARGET_ENE_0, AI_DIR_TYPE_R, 180) then
        Donsyoku526000_Now(goal, 3000)
    else
        Donsyoku526000_Now(goal, 3010)
    end
end

-- 3001 left hand slams the ground several times
function Donsyoku526000_Act02(ai, goal)
    ai:SetTimer(4, 20)
    Donsyoku526000_Approach(ai, goal, 1.5)
    Donsyoku526000_Front(goal, 3001)
end

-- 3002 left hand swipe
function Donsyoku526000_Act03(ai, goal)
    ai:SetNumber(3, 1)
    Donsyoku526000_Approach(ai, goal, 4)
    Donsyoku526000_Front(goal, 3002)
end

-- 3003 belly flop forward, always runs on into the 3004 charge (25 m)
function Donsyoku526000_Act04(ai, goal)
    ai:SetTimer(0, 35)
    Donsyoku526000_Approach(ai, goal, 25)
    goal:AddSubGoal(GOAL_COMMON_CommonAttack, 15, 3003, TARGET_ENE_0, DIST_None, 180, 1.5, 30, true, true, false, false, 0, 0)
    goal:AddSubGoal(GOAL_COMMON_ComboFinal, 30, 3004, TARGET_ENE_0, DIST_Middle, 0)
end

-- tail whip (3006 once the tail is cut)
function Donsyoku526000_Act05(ai, goal)
    local PARTS_IDX_TAIL = 0
    ai:SetTimer(3, 20)
    if ai:GetPartsDmg(PARTS_IDX_TAIL) == PARTS_DMG_FINAL then
        Donsyoku526000_Now(goal, 3006)
    else
        Donsyoku526000_Now(goal, 3005)
    end
end

-- 3007 jump straight up and crush (in place)
function Donsyoku526000_Act06(ai, goal)
    ai:SetTimer(2, 20)
    Donsyoku526000_Now(goal, 3007)
end

-- 3008 big acid vomit
function Donsyoku526000_Act07(ai, goal)
    ai:SetNumber(1, 1)
    ai:SetTimer(1, 40)
    Donsyoku526000_Front(goal, 3008)
end

-- 3009 jump forward and crush (16.8 m); closer than 8 m: jump in place
function Donsyoku526000_Act08(ai, goal)
    ai:SetTimer(2, 20)
    if ai:GetDist(TARGET_ENE_0) < 8 then
        Donsyoku526000_Front(goal, 3007)
    else
        Donsyoku526000_Approach(ai, goal, 14)
        Donsyoku526000_Front(goal, 3009)
    end
end

function Donsyoku526000_Act30(ai, goal)
    goal:AddSubGoal(GOAL_COMMON_ApproachTarget, 2.5, TARGET_ENE_0, 6, TARGET_ENE_0, true, -1)
end

function Donsyoku526000_Act31(ai, goal)
    goal:AddSubGoal(GOAL_COMMON_LeaveTarget, 2.5, TARGET_ENE_0, 10, TARGET_ENE_0, true, -1)
end

function Donsyoku526000_Act32(ai, goal)
    goal:AddSubGoal(GOAL_COMMON_Turn, 3, TARGET_ENE_0, 90, 0, 0)
end

function Donsyoku526000Battle_Update(ai, goal)
    return GOAL_RESULT_Continue
end

function Donsyoku526000Battle_Terminate(ai, goal)
    return
end

function Donsyoku526000Battle_Interupt(ai, goal)
    if ai:IsInterupt(INTERUPT_SuccessThrow) then
        goal:ClearSubGoal()
        goal:AddSubGoal(GOAL_COMMON_LeaveTarget, 6, TARGET_ENE_0, 10, TARGET_ENE_0, true, -1)
        return true
    end
    return false
end

return
'''


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-build", action="store_true", help="write the .lua only")
    args = ap.parse_args(argv)
    if re.search(r"\d,\d", LUA):
        raise RuntimeError("decimal comma in the script")
    OUT_LUA.write_text(LUA, encoding="shift_jis", newline="\n")
    print(f"written {OUT_LUA} ({len(LUA.splitlines())} lines)")
    if args.no_build:
        return 0
    OUT_BND.parent.mkdir(parents=True, exist_ok=True)
    return subprocess.call([sys.executable, str(ROOT / "tools" / "ai_lua.py"), "build", "m10_00_00_00",
                            "526000_battle.lua", str(OUT_LUA), str(OUT_BND)])


if __name__ == "__main__":
    sys.exit(main())
